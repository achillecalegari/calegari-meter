"""The AS7341's eight visible channels -> CIE XYZ: a 3 x 8 matrix, least squares against the CIE 1931 2 degree
colour matching functions, written to firmware/src/color_model.h with the channels' response model (used on
the meter to compute what each channel should read under a lamp of known temperature, for calibration).

Channels: centre and FWHM from the AS7341 datasheet (F1..F8). Response modelled as Gaussians of equal peak;
the calibration under a lamp of known temperature measures each channel's real gain, diffuser included.
CMFs: Wyman, Sloan and Shirley (2013) multi-lobe fit."""
import math, pathlib
import numpy as np

CH = [(415, 26), (445, 30), (480, 36), (515, 39), (555, 39), (590, 40), (630, 50), (680, 52)]
L = np.arange(380, 781, 5.0)


def g(x, mu, s1, s2):
    s = np.where(x < mu, s1, s2)
    return np.exp(-0.5 * ((x - mu) / s) ** 2)


def cmf(l):
    x = 1.056 * g(l, 599.8, 37.9, 31.0) + 0.362 * g(l, 442.0, 16.0, 26.7) - 0.065 * g(l, 501.1, 20.4, 26.2)
    y = 0.821 * g(l, 568.8, 46.9, 40.5) + 0.286 * g(l, 530.9, 16.3, 31.1)
    z = 1.217 * g(l, 437.0, 11.8, 36.0) + 0.681 * g(l, 459.0, 26.0, 13.8)
    return np.stack([x, y, z])


def resp(l):
    return np.stack([np.exp(-0.5 * ((l - c) / (w / 2.3548)) ** 2) for c, w in CH])


def planck(l_nm, t):
    l = l_nm * 1e-9
    return 1.0 / (l ** 5 * (np.exp(1.4388e-2 / (l * t)) - 1.0))


def main():
    R = resp(L)                    # 8 x n
    C = cmf(L)                     # 3 x n
    # M R ~ C over a set of smooth spectra (blackbodies and daylight-like tilts) rather than per wavelength:
    # the fit then serves the lights a photographer meets
    spectra = [planck(L, t) for t in np.linspace(2000, 12000, 41)]
    spectra += [planck(L, t) * (1 + a * (L - 560) / 200) for t in (3000, 5000, 6500, 9000) for a in (-0.3, 0.3)]
    S = np.stack([s / s.max() for s in spectra], axis=1)          # n x k
    Rs, Cs = R @ S, C @ S                                         # 8 x k, 3 x k
    M = Cs @ np.linalg.pinv(Rs)                                   # 3 x 8
    err = np.abs(M @ Rs - Cs).max() / Cs.max()
    # check: blackbodies through the model, CCT back by McCamy
    worst = 0
    for t in (2500, 3200, 4000, 5500, 6500, 8000, 10000):
        X, Y, Z = M @ (R @ planck(L, t))
        x, y = X / (X + Y + Z), Y / (X + Y + Z)
        n = (x - 0.3320) / (0.1858 - y)
        cct = 449 * n ** 3 + 3525 * n ** 2 + 6823.3 * n + 5520.33
        worst = max(worst, abs(cct - t) / t)
        print(f"{t:6d} K -> {cct:7.0f} K")
    out = ["// Generated by tools/colorgen.py. Do not edit.", "#pragma once", "",
           "// AS7341 F1..F8: centre and FWHM (nm), modelled as Gaussians of equal peak",
           "static const float CH_NM[8] = {" + ", ".join(f"{c}.0f" for c, _ in CH) + "};",
           "static const float CH_FWHM[8] = {" + ", ".join(f"{w}.0f" for _, w in CH) + "};",
           "// channels -> CIE XYZ (least squares over blackbodies 2000..12000 K and tilted daylights)",
           "static const float CH_TO_XYZ[3][8] = {"]
    for row in M:
        out.append("  {" + ", ".join(f"{v:.6g}f" for v in row) + "},")
    out.append("};")
    (pathlib.Path(__file__).resolve().parents[1] / "firmware/src/color_model.h").write_text("\n".join(out) + "\n")
    print(f"fit error {err:.3%}, worst CCT error {worst:.2%}")


if __name__ == "__main__":
    main()
