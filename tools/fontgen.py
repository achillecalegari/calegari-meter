"""Bake Inter into anti-aliased 4-bit glyph tables for the firmware (firmware/src/fonts.cpp).

Each font is one size, one weight and one optical size of the variable Inter. Digits are tabular, so a
changing reading does not shift sideways. Characters beyond ASCII are mapped to single bytes from 0x80,
listed in EXTRA, and written in C strings as escapes (fonts.h names them)."""
import pathlib
from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parents[1]
TTF = ROOT / "tools/fonts/Inter.ttf"
OUT = ROOT / "firmware/src"

EXTRA = [("PLUSMINUS", "±"), ("MINUS", "−"), ("THIRD", "⅓"), ("TWOTHIRDS", "⅔"),
         ("MIDDOT", "·"), ("ARROW", "→"), ("LSAQUO", "‹"), ("RSAQUO", "›"),
         ("DEGREE", "°"), ("PRIME2", "″"), ("TIMES", "×")]
ASCII = "".join(chr(c) for c in range(32, 127))
EXTRA_CHARS = "".join(c for _, c in EXTRA)

# name, pixel size, weight, optical size, characters
FONTS = [
    ("F_HUGE", 128, 340, 32, " 0123456789/.s\u2033mKN+" + EXTRA_CHARS),
    ("F_BIG", 64, 400, 32, " 0123456789/.fsmK+NABCDEFone" + EXTRA_CHARS),
    ("F_MED", 36, 460, 28, ASCII + EXTRA_CHARS),
    ("F_SMALL", 25, 520, 20, ASCII + EXTRA_CHARS),
    ("F_TINY", 19, 560, 16, ASCII + EXTRA_CHARS),
]


def code_of(ch):
    for i, (_, c) in enumerate(EXTRA):
        if c == ch:
            return 0x80 + i
    return ord(ch)


def bake(name, px, wght, opsz, chars):
    f = ImageFont.truetype(str(TTF), px)
    f.set_variation_by_axes([opsz, wght])
    asc, desc = f.getmetrics()
    tnum = max(f.getlength(d, features=["tnum"]) for d in "0123456789")
    glyphs, data = {}, bytearray()
    for ch in sorted(set(chars), key=code_of):
        adv = f.getlength(ch, features=["tnum"]) if ch.isdigit() else f.getlength(ch)
        if ch.isdigit():
            adv = tnum
        im = Image.new("L", (px * 3, px * 3), 0)
        ImageDraw.Draw(im).text((px, px), ch, font=f, fill=255, features=["tnum"] if ch.isdigit() else None)
        bb = im.getbbox()
        if bb is None:
            glyphs[code_of(ch)] = (len(data), 0, 0, 0, 0, round(adv))
            continue
        x0, y0, x1, y1 = bb
        w, h = x1 - x0, y1 - y0
        off = len(data)
        for y in range(h):
            row = [im.getpixel((x0 + x, y0 + y)) >> 4 for x in range(w)]
            if w % 2:
                row.append(0)
            for i in range(0, len(row), 2):
                data.append((row[i] << 4) | row[i + 1])
        # offsets relative to the pen: x from the pen position, y from the baseline (negative = above)
        glyphs[code_of(ch)] = (off, w, h, x0 - px, y0 - (px + asc), round(adv))
    first, last = min(glyphs), max(glyphs)
    return dict(name=name, data=data, glyphs=glyphs, first=first, last=last, asc=asc, desc=desc,
                cap=-glyphs[code_of("0")][4] if code_of("0") in glyphs else asc)


def main():
    fonts = [bake(*spec) for spec in FONTS]
    h = ["// Generated by tools/fontgen.py from Inter (SIL Open Font License). Do not edit.",
         "#pragma once", "#include <stdint.h>", "",
         "struct Glyph { uint32_t off; uint8_t w, h; int8_t dx, dy; uint8_t adv; };",
         "struct Font { const uint8_t *bits; const Glyph *glyphs; uint8_t first, last; uint8_t asc, desc, cap; };", ""]
    for i, (n, c) in enumerate(EXTRA):
        h.append(f'#define G_{n} "\\x{0x80 + i:02x}"')
    h.append("")
    for fo in fonts:
        h.append(f"extern const Font {fo['name']};")
    (OUT / "fonts.h").write_text("\n".join(h) + "\n")

    c = ["// Generated by tools/fontgen.py from Inter (SIL Open Font License). Do not edit.",
         '#include "fonts.h"', ""]
    for fo in fonts:
        n = fo["name"].lower()
        c.append(f"static const uint8_t {n}_bits[] = {{")
        d = fo["data"]
        for i in range(0, len(d), 24):
            c.append("  " + ",".join(str(b) for b in d[i:i + 24]) + ",")
        c.append("};")
        c.append(f"static const Glyph {n}_glyphs[] = {{")
        for code in range(fo["first"], fo["last"] + 1):
            g = fo["glyphs"].get(code, (0, 0, 0, 0, 0, 0))
            c.append("  {%d,%d,%d,%d,%d,%d}," % g)
        c.append("};")
        c.append(f"const Font {fo['name']} = {{{n}_bits, {n}_glyphs, {fo['first']}, {fo['last']}, "
                 f"{fo['asc']}, {fo['desc']}, {fo['cap']}}};")
        c.append("")
    (OUT / "fonts.cpp").write_text("\n".join(c) + "\n")
    for fo in fonts:
        print(f"{fo['name']}: {len(fo['glyphs'])} glyphs, {len(fo['data'])} bytes, cap {fo['cap']} px")


if __name__ == "__main__":
    main()
